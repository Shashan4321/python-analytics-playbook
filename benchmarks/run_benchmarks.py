"""Time the patterns in this repo and write benchmarks/RESULTS.md.

Usage:  python benchmarks/run_benchmarks.py [--rows 1000000]
"""

from __future__ import annotations

import argparse
import platform
import statistics
import sys
import time
from collections.abc import Callable
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import duckdb  # noqa: E402
import pandas as pd  # noqa: E402
import polars as pl  # noqa: E402

from playbook.data import make_sales  # noqa: E402
from playbook.engines import (  # noqa: E402
    category_revenue_duckdb,
    category_revenue_pandas,
    category_revenue_polars,
)
from playbook.performance import (  # noqa: E402
    discount_band_apply,
    discount_band_select,
    memory_mb,
    optimize_dtypes,
    revenue_loop,
    revenue_vectorized,
)


def best_of(fn: Callable[[], object], repeats: int = 3) -> float:
    """Median wall time in seconds over `repeats` runs."""
    times = []
    for _ in range(repeats):
        start = time.perf_counter()
        fn()
        times.append(time.perf_counter() - start)
    return statistics.median(times)


def fmt(seconds: float) -> str:
    return f"{seconds * 1000:,.1f} ms" if seconds < 1 else f"{seconds:,.2f} s"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rows", type=int, default=1_000_000)
    args = parser.parse_args()

    print(f"Generating {args.rows:,} rows ...")
    df = make_sales(n_orders=args.rows, seed=42)
    loop_sample = df.head(200_000)

    lines = [
        "# Benchmark results",
        "",
        f"Generated by `benchmarks/run_benchmarks.py` on {args.rows:,} synthetic order lines.",
        f"Machine: {platform.processor() or platform.machine()}, {platform.system()} {platform.release()}, "
        f"Python {platform.python_version()}, pandas {pd.__version__}, Polars {pl.__version__}, "
        f"DuckDB {duckdb.__version__}. Median of 3 runs. Your numbers will differ; the ratios are the point.",
        "",
    ]

    # 1. Memory
    before = memory_mb(df)
    small = optimize_dtypes(df)
    after = memory_mb(small)
    lines += [
        "## 1. Memory: `optimize_dtypes`",
        "",
        "| | Memory |",
        "|---|---:|",
        f"| Default dtypes | {before:,.1f} MB |",
        f"| Downcast numbers + categoricals | {after:,.1f} MB |",
        f"| **Saving** | **{1 - after / before:.0%}** |",
        "",
    ]

    # 2. Vectorisation
    t_loop = best_of(lambda: revenue_loop(loop_sample))
    t_vec = best_of(lambda: revenue_vectorized(loop_sample))
    t_apply = best_of(lambda: discount_band_apply(loop_sample))
    t_select = best_of(lambda: discount_band_select(loop_sample))
    lines += [
        f"## 2. Vectorisation ({len(loop_sample):,} rows)",
        "",
        "| Task | Slow pattern | Fast pattern | Speed-up |",
        "|---|---:|---:|---:|",
        f"| Line revenue | `itertuples` loop: {fmt(t_loop)} | column maths: {fmt(t_vec)} "
        f"| **{t_loop / t_vec:,.0f}x** |",
        f"| Discount band (2-column rule) | `.apply(axis=1)`: {fmt(t_apply)} | `np.select`: {fmt(t_select)} "
        f"| **{t_apply / t_select:,.0f}x** |",
        "",
    ]

    # 3. Engines: each works on data already in its own format (conversion timed separately).
    native = pl.from_pandas(df)
    con = duckdb.connect()
    con.register("sales_df", df)
    t_load = best_of(lambda: con.execute("CREATE OR REPLACE TABLE sales_tbl AS SELECT * FROM sales_df"), 1)
    con.unregister("sales_df")
    timings = {
        "pandas": best_of(lambda: category_revenue_pandas(df)),
        "Polars (lazy)": best_of(lambda: category_revenue_polars(native)),
        "DuckDB (native table)": best_of(lambda: category_revenue_duckdb("sales_tbl", con)),
        "DuckDB (querying the pandas DataFrame)": best_of(lambda: category_revenue_duckdb(df, con)),
    }
    fastest = min(timings.values())
    lines += [
        "## 3. Same KPI, three engines",
        "",
        "Net revenue and distinct orders per fiscal year and category. All engines return identical results "
        "(checked in `tests/test_performance_and_engines.py`).",
        "",
        "| Engine | Time | vs fastest |",
        "|---|---:|---:|",
        *[f"| {name} | {fmt(t)} | {t / fastest:,.1f}x |" for name, t in timings.items()],
        "",
        f"Loading the DataFrame into a DuckDB table once took {fmt(t_load)}. Querying a pandas DataFrame "
        "directly pays a conversion cost on every query, so for repeated queries load once "
        "(or read Parquet) and query the table.",
        "",
    ]

    out = Path(__file__).with_name("RESULTS.md")
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nWritten to {out}")


if __name__ == "__main__":
    main()
